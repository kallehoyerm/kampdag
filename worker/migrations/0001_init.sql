CREATE TABLE IF NOT EXISTS results (
  dato TEXT NOT NULL,
  klient TEXT NOT NULL,
  total INTEGER NOT NULL CHECK(total BETWEEN 0 AND 700),
  r1 INTEGER NOT NULL, r2 INTEGER NOT NULL, r3 INTEGER NOT NULL,
  r4 INTEGER NOT NULL, r5 INTEGER NOT NULL, r6 INTEGER NOT NULL, r7 INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (dato, klient)
);
CREATE INDEX IF NOT EXISTS results_by_date ON results(dato, total);
CREATE TABLE IF NOT EXISTS rate_windows (
  klient TEXT NOT NULL,
  minute TEXT NOT NULL,
  count INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (klient, minute)
);
